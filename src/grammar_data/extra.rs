//! Second batch of rules, added after a review against reference grammars.
//!
//! Each block is appended to an existing branch of the tree (named by its
//! Turkish title path) with `add`. New rules can go either here or directly
//! into `grammar_data.rs`; the result is the same tree.

use super::{add, b, l, NodeDef};

pub(super) fn extend_grammar(root: &mut NodeDef) {
    add(root, &["Ses Bilgisi"], vec![alphabet()]);
    add(root, &["Ses Bilgisi", "Yazım & Söyleyiş"], spelling());
    add(root, &["İsimler & Çekim"], vec![location_nouns(), determiners()]);
    add(root, &["Zamirler"], pronouns());
    add(root, &["Sıfatlar & Zarflar"], vec![reduplication(), time_expressions()]);
    add(root, &["Sayılar"], numbers());
    add(root, &["Fiiller & Zamanlar", "Basit Zamanlar"], simple_tenses());
    add(root, &["Fiiller & Zamanlar", "Birleşik Zamanlar"], compound_tenses());
    add(root, &["Fiiller & Zamanlar", "Fiil Çatısı"], voice());
    add(root, &["Fiiller & Zamanlar"], vec![modality(), requests(), aspect()]);
    add(root, &["Fiilimsiler"], vec![adverbial_clauses()]);
    add(root, &["Yapım Ekleri", "İsimden İsim"], noun_to_noun());
    add(root, &["Yapım Ekleri", "İsimden Fiil"], noun_to_verb());
    add(root, &["Yapım Ekleri", "Fiilden İsim"], verb_to_noun());
    add(root, &["Yapım Ekleri"], vec![compounds()]);
    add(root, &["Cümle Yapısı", "Edatlar"], postpositions());
    add(root, &["Cümle Yapısı"], clause_details());
    add(root, &["Cümle Yapısı"], vec![question_types(), conversation()]);
}

