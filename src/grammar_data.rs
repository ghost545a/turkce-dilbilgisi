#[cfg(test)]
mod tests {
    use super::*;

    fn walk(n: &NodeDef, depth: usize, f: &mut dyn FnMut(&NodeDef, usize)) {
        f(n, depth);
        for c in &n.children {
            walk(c, depth + 1, f);
        }
    }

    #[test]
    fn has_ten_primary_rings() {
        assert_eq!(grammar().children.len(), 10);
    }

    #[test]
    fn by_level_holds_every_rule_exactly_once() {
        let count = |root: &NodeDef| {
            let mut n = 0;
            walk(root, 0, &mut |x, _| if x.children.is_empty() { n += 1 });
            n
        };
        let house = by_level();
        assert_eq!(house.children.len(), 6);
        assert_eq!(count(&house), count(&grammar()));
        for (floor, &(level, _, _)) in house.children.iter().zip(LEVELS.iter()) {
            assert_eq!(floor.tr, level);
            assert!(!floor.children.is_empty(), "floor {level} is empty");
            walk(floor, 0, &mut |x, _| if x.children.is_empty() { assert_eq!(x.level, level, "{}", x.tr) });
            if level == "C1" || level == "C2" {
                assert!(count(floor) >= 6, "floor {level} has only {} rules", count(floor));
            }
        }
    }

    #[test]
    fn every_leaf_is_complete() {
        let mut leaves = 0;
        walk(&grammar(), 0, &mut |n, _| {
            assert!(!n.tr.is_empty() && !n.en.is_empty() && !n.harmony.is_empty(), "{}", n.tr);
            if n.children.is_empty() {
                leaves += 1;
                assert_eq!(n.examples.len(), 3, "{}", n.tr);
                assert!(!n.formula.is_empty() && !n.notes.is_empty(), "{}", n.tr);
                assert!(["A1", "A2", "B1", "B2", "C1", "C2"].contains(&n.level), "{}: {}", n.tr, n.level);
                for e in &n.examples {
                    let open = e.tr.matches('[').count();
                    assert!(open >= 1 && open == e.tr.matches(']').count(), "{}", e.tr);
                    let mut inside = false;
                    for c in e.tr.chars() {
                        match c {
                            '[' => { assert!(!inside, "{}", e.tr); inside = true; }
                            ']' => { assert!(inside, "{}", e.tr); inside = false; }
                            _ => {}
                        }
                    }
                    assert!(!e.en.is_empty() && !e.en.contains('['), "{}", e.tr);
                }
            } else {
                assert!(n.examples.is_empty());
            }
        });
        assert!(leaves >= 345, "only {leaves} leaves");
    }
}
