//! The Turkish grammar tree.
//!
//! To add a rule, drop one more `l(...)` call (a leaf) into the `vec![...]`
//! of the branch it belongs to, or wrap a group of leaves in `b(...)` to make
//! a new branch. Nothing else needs to change: the runtime flattens whatever
//! tree `grammar()` returns.
//!
//! Notation used in formulas:
//!   A = e / a (2-way harmony)      I = ı / i / u / ü (4-way harmony)
//!   D = d / t, C = c / ç, G = g / k (consonant assimilation)
//!   (y), (s), (n), (I) = appears only when needed as a buffer
//!
//! In example sentences the part to highlight is wrapped in [square brackets].

use serde::Serialize;

mod extra;
mod institutes;
use extra::extend_grammar;
use institutes::extend_institutes;

#[derive(Clone, Serialize)]
pub struct Example {
    /// Turkish sentence; `[...]` marks the suffix or word being illustrated.
    pub tr: &'static str,
    pub en: &'static str,
}

#[derive(Clone, Serialize)]
pub struct NodeDef {
    /// Turkish title (also the label drawn on the map).
    pub tr: &'static str,
    /// English title.
    pub en: &'static str,
    /// CEFR level, `A1`..`C2` (a range such as `A1–B2` for branches).
    pub level: &'static str,
    /// Suffix formula; empty for branches.
    pub formula: &'static str,
    /// Harmony breakdown (leaves) or overview (branches).
    pub harmony: &'static str,
    /// Exceptions and usage notes.
    pub notes: &'static str,
    pub examples: Vec<Example>,
    #[serde(skip)]
    pub children: Vec<NodeDef>,
}

/// Branch node.
fn b(tr: &'static str, en: &'static str, level: &'static str, overview: &'static str, children: Vec<NodeDef>) -> NodeDef {
    NodeDef { tr, en, level, formula: "", harmony: overview, notes: "", examples: Vec::new(), children }
}

/// Leaf rule with exactly three example sentences `(turkish, english)`.
fn l(
    tr: &'static str,
    en: &'static str,
    level: &'static str,
    formula: &'static str,
    harmony: &'static str,
    notes: &'static str,
    examples: [(&'static str, &'static str); 3],
) -> NodeDef {
    NodeDef {
        tr,
        en,
        level,
        formula,
        harmony,
        notes,
        examples: examples.iter().map(|&(tr, en)| Example { tr, en }).collect(),
        children: Vec::new(),
    }
}

pub fn grammar() -> NodeDef {
    let mut root = b(
        "Türkçe Dilbilgisi",
        "Turkish Grammar",
        "A1–C2",
        "Turkish is an agglutinative, verb-final language: meaning is built by chaining suffixes onto a root, and every suffix adapts to the root through vowel and consonant harmony.",
        vec![
            phonology(), nouns(), pronouns(), adjectives(), numbers(),
            verbs(), copula(), verbals(), derivation(), syntax(),
        ],
    );
    extend_grammar(&mut root);
    extend_institutes(&mut root);
    root
}

/// Append `extra` to the node reached by following `path` (Turkish titles)
/// down from `root`.
fn add(root: &mut NodeDef, path: &[&str], extra: Vec<NodeDef>) {
    let mut node = root;
    for step in path {
        node = node
            .children
            .iter_mut()
            .find(|c| c.tr == *step)
            .unwrap_or_else(|| panic!("no branch named {step}"));
    }
    node.children.extend(extra);
}

/// The six CEFR floors, ground floor first: (level, Turkish · English name, overview).
pub const LEVELS: [(&str, &str, &str); 6] = [
    ("A1", "Başlangıç · Beginner", "The ground floor: vowel harmony, the six cases, possessives, ‘to be’, the present continuous and definite past, numbers and question words."),
    ("A2", "Temel · Elementary", "Everyday range: aorist, future and evidential past, ability, comparison, the first converbs and noun compounds."),
    ("B1", "Orta · Intermediate", "Connected speech: participles and relative clauses, passive and causative, conditionals, noun clauses and most postpositions."),
    ("B2", "Orta Üstü · Upper-intermediate", "Nuance and register: reported speech, compound tenses of hearsay, formal progressive and finer derivation."),
    ("C1", "İleri · Advanced", "Formal and idiomatic structures: periphrastic tenses, rare converbs and written-register connectors."),
    ("C2", "Ustalık · Mastery", "The attic: literary, archaic and Ottoman-era patterns needed for older texts and elevated prose."),
];

fn collect_leaves(n: &NodeDef, level: &str, out: &mut Vec<NodeDef>) {
    if n.children.is_empty() {
        if n.level == level {
            out.push(n.clone());
        }
    } else {
        for c in &n.children {
            collect_leaves(c, level, out);
        }
    }
}

/// The same rules regrouped for the "study by level" view:
/// Türkçe → A1 … C2 → topic (the primary ring a rule comes from) → rules.
pub fn by_level() -> NodeDef {
    let all = grammar();
    let floors = LEVELS
        .iter()
        .map(|&(level, name, overview)| {
            let rooms = all
                .children
                .iter()
                .filter_map(|ring| {
                    let mut leaves = Vec::new();
                    collect_leaves(ring, level, &mut leaves);
                    (!leaves.is_empty()).then(|| b(ring.tr, ring.en, level, ring.harmony, leaves))
                })
                .collect();
            b(level, name, level, overview, rooms)
        })
        .collect();
    b(
        "Türkçe",
        "Turkish by Level",
        "A1–C2",
        "The same grammar arranged as a house of six floors. Start on the ground floor (A1) and climb: each floor holds the rules usually learned at that CEFR level, grouped by topic.",
        floors,
    )
}

